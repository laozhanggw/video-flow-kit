def load_instructions():
    data = {}
    for k, fn in INSTR_FILES.items():
        p = os.path.join(TPL, fn)
        if not os.path.exists(p):
            print("缺文件:", p)
            continue
        data[k] = io.open(p, encoding="utf-8").read()
    return data


def load_skills():
    data = {}
    for key, rel, label in SKILL_FILES:
        p = os.path.join(SKILL_DIR, *rel.split("/"))
        if not os.path.exists(p):
            print("缺 skill 文件:", p)
            continue
        data[key] = {"label": label, "path": "skills/" + rel,
                     "text": io.open(p, encoding="utf-8").read()}
    return data


def build():
    instr = load_instructions()
    skills = load_skills()
    payload = json.dumps({"nodes": NODES, "instr": instr, "skills": skills}, ensure_ascii=False)
    html = HTML_TEMPLATE.replace("/*__DATA__*/", "const DATA = " + payload + ";")

    # 版本条：生成时间 + 五份指令字数。字数即指纹，页面与 txt 对不上就说明没同步。
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    cells = "".join(
        '<span class="vc"><b>{k}</b> {n:,}</span>'.format(k=k, n=len(instr.get(k, "")))
        for k in sorted(INSTR_FILES)
    )
    sk_cells = "".join(
        '<span class="vc"><b>s{}</b> {:,}</span>'.format(i + 1, len(v["text"]))
        for i, (k, v) in enumerate(skills.items())
    )
    ver = ('<span class="vt">生成于 <b>{s}</b></span>'
           '<span class="vsep"></span>'
           '<span class="vl">指令字数</span>{c}'
           '<span class="vsep"></span>'
           '<span class="vl">skill 字数</span>{sc}'
           '<span class="grow"></span>'
           '<span class="vh">页面字数与本机文件不一致，说明没重跑生成器</span>'
           ).format(s=stamp, c=cells, sc=sk_cells)
    html = html.replace("<!--__VER__-->", ver)

    io.open(OUT, "w", encoding="utf-8", newline="\n").write(html)
    print("已生成:", OUT)
    print("生成时间:", stamp)
    print("指令文件:", ", ".join(f"{k}={len(v)}字" for k, v in instr.items()))
    print("skill 文件:", ", ".join(f"{k}={len(v['text'])}字" for k, v in skills.items()))


